def build_claims() -> dict:
    result = read_json("claims.json")
    result["schema_version"] = "0.2-candidate"
    result["benchmark_id"] = "alphabet-2025-business-map-v0.2-candidate"
    old_ids = {line["old_claim"] for line in LINE_DEFINITIONS}
    claims = [item for item in result["claims"] if item["id"] not in old_ids]
    insertion = next(index for index, item in enumerate(claims) if item["id"] == "advertising-definition") + 1
    promoted = [claim for line in LINE_DEFINITIONS for claim in build_line_claims(line)]
    claims[insertion:insertion] = promoted
    result["claims"] = claims
    result["status"] = "candidate"
    return result


def build_spans() -> dict:
    result = read_json("evidence_spans.json")
    result["schema_version"] = "0.2-candidate"
    old_ids = {line["old_claim"] for line in LINE_DEFINITIONS}
    templates = {(item["claim_id"], item["evidence_id"]): item for item in result["spans"]}
    spans = [item for item in result["spans"] if item["claim_id"] not in old_ids]

    for line in LINE_DEFINITIONS:
        prefix = line["id"]
        sources = (
            (f"{prefix}-identity-parent", "advertising-definition", "e-ad-components"),
            (f"{prefix}-identity-parent", line["old_claim"], line["specific_evidence"]),
            (f"{prefix}-description", line["old_claim"], line["specific_evidence"]),
            (f"{prefix}-monetization", "services-advertising-model", "e-services-advertising"),
            (f"{prefix}-revenue-2025", line["old_claim"], "e-revenue-table"),
        )
        for new_claim_id, template_claim_id, evidence_id in sources:
            span = copy.deepcopy(templates[(template_claim_id, evidence_id)])
            span["claim_id"] = new_claim_id
            spans.append(span)

    result["spans"] = spans
    return result


